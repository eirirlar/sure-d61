"""Rebuild TASKS_INDEX.md and ARCHIVE_INDEX.md from TASKS.md and ARCHIVE.md.

Both index files are script-maintained TOCs — one line per task with status
marker, title and a GitHub-style anchor link into the source file. They exist
so a reader does not have to grep a 4000-line master file to see what is open
or what has been solved.

Run after any edit that touches a task header in TASKS.md or ARCHIVE.md:
status toggle, title change, new task, or move between the two files.

Default mode is write. ``--check`` exits non-zero if the stored indexes drift
from what would be regenerated from the current source files.

Ported from ../stotte/.claude/skills/archive-tasks/archive_tasks.py (index
portion only — this repo does archiving by explicit manual move rather than
via a script).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TASKS = REPO_ROOT / "TASKS.md"
ARCHIVE = REPO_ROOT / "ARCHIVE.md"
TASKS_INDEX = REPO_ROOT / "TASKS_INDEX.md"
ARCHIVE_INDEX = REPO_ROOT / "ARCHIVE_INDEX.md"

TASK_HEADER = re.compile(r"^### T(\d+(?:\.\d+)*)\s+`\[([ ~x])\]`\s+(.*)$")


def heading_to_anchor(tid: str, status: str, title_rest: str) -> str:
    r"""GitHub-style anchor for a `### T<n> \`[s]\` title` heading.

    Lowercase the full heading text, replace whitespace with hyphens,
    strip anything that is not ASCII alphanumeric / hyphen / underscore,
    collapse repeated hyphens, strip leading/trailing hyphens.
    """
    s = f"T{tid} `[{status}]` {title_rest}".lower()
    s = re.sub(r"\s+", "-", s)
    s = re.sub(r"[^a-z0-9\-_]", "", s)
    s = re.sub(r"-+", "-", s)
    return s.strip("-")


def parse_tasks(text: str) -> list[tuple[str, str, str]]:
    """Return [(tid, status, title_rest), ...] in file order."""
    out = []
    for line in text.splitlines():
        m = TASK_HEADER.match(line)
        if m:
            out.append((m.group(1), m.group(2), m.group(3)))
    return out


def build_index(
    headers: list[tuple[str, str, str]],
    source_file: str,
    title: str,
) -> str:
    counts = {" ": 0, "~": 0, "x": 0}
    for _tid, status, _title in headers:
        counts[status] = counts.get(status, 0) + 1
    total = len(headers)
    lines = [
        f"# {title}",
        "",
        "**Script-maintained — never hand-edit.** Regenerated by "
        "`python scripts/rebuild_task_indexes.py`. Run after any status "
        "toggle, resolution block, new task, or archive move.",
        "",
        f"{total} task entr{'ies' if total != 1 else 'y'} "
        f"(`[x]` {counts.get('x', 0)} · "
        f"`[~]` {counts.get('~', 0)} · "
        f"`[ ]` {counts.get(' ', 0)}).",
        "",
    ]
    for tid, status, title_rest in headers:
        anchor = heading_to_anchor(tid, status, title_rest)
        lines.append(
            f"- [T{tid}]({source_file}#{anchor}) `[{status}]` {title_rest}"
        )
    lines.append("")
    return "\n".join(lines)


def regenerate() -> tuple[str, str]:
    tasks_headers = parse_tasks(TASKS.read_text(encoding="utf-8"))
    arch_headers = parse_tasks(ARCHIVE.read_text(encoding="utf-8"))
    return (
        build_index(tasks_headers, "TASKS.md", "TASKS.md index"),
        build_index(arch_headers, "ARCHIVE.md", "ARCHIVE.md index"),
    )


def check() -> list[str]:
    tasks_idx, arch_idx = regenerate()
    issues = []
    for path, expected in ((TASKS_INDEX, tasks_idx), (ARCHIVE_INDEX, arch_idx)):
        if not path.exists():
            issues.append(f"{path.name} missing")
            continue
        if path.read_text(encoding="utf-8") != expected:
            issues.append(f"{path.name} drift (contents differ from regenerated output)")
    return issues


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="print drift (if any) and exit non-zero on drift; no writes",
    )
    args = ap.parse_args(argv)

    if args.check:
        issues = check()
        if not issues:
            print(
                "Indexes OK — TASKS_INDEX.md and ARCHIVE_INDEX.md match the "
                "current source files.",
                file=sys.stderr,
            )
            return 0
        for issue in issues:
            print(f"DRIFT: {issue}", file=sys.stderr)
        print("Run `python scripts/rebuild_task_indexes.py` to regenerate.", file=sys.stderr)
        return 1

    tasks_idx, arch_idx = regenerate()
    TASKS_INDEX.write_text(tasks_idx, encoding="utf-8")
    ARCHIVE_INDEX.write_text(arch_idx, encoding="utf-8")
    print(f"Wrote {TASKS_INDEX.name} and {ARCHIVE_INDEX.name}.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
